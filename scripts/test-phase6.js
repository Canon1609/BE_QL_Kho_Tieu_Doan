// Run ONLY with DB_NAME=ql_kho_tieu_doan_5_phase6_verify (separate test database).
const assert = require('node:assert/strict');
const { sequelize, Unit, Location, Material, MaterialSource, ConditionLevel, StockLedgerEntry: Ledger, MaterialCategory, UnitOfMeasure } = require('../src/models');
const loc = require('../src/services/location-management.service');
const transfer = require('../src/services/transfer.service');
const stamp = `P6_${Date.now()}`;
const reject = async (fn, status) => assert.equal((await fn().then(() => null, e => e))?.statusCode, status);
async function main() {
  if (process.env.DB_NAME !== 'ql_kho_tieu_doan_5_phase6_verify') throw Error('Refusing non-test DB');
  const [root, c11, c13] = await Promise.all(['BATTALION_5', 'COMPANY_11', 'COMPANY_13'].map(code => Unit.findOne({ where: { code } })));
  const admin = { id: (await require('../src/models').User.findOne({ where: { unit_id: root.id } })).id, is_active: true, unit_id: root.id, unit: root, role: { code: 'BATTALION_ADMIN' } };
  const user11 = { ...admin, unit_id: c11.id, unit: c11, role: { code: 'COMPANY_ADMIN' } };
  const category = await MaterialCategory.create({ code: stamp, name: 'Loại thử nghiệm' });
  const measure = await UnitOfMeasure.findOne({ where: { is_active: true } });
  const material = await Material.create({ code: stamp, name: 'Quạt thử nghiệm', category_id: category.id, unit_id: measure.id });
  const source = await MaterialSource.findOne({ where: { is_active: true } });
  const condition = await ConditionLevel.findOne({ where: { is_active: true } });
  const rootStore = await Location.findOne({ where: { code: 'LOC_BATTALION_5_WAREHOUSE' } });
  const companyStore = await Location.findOne({ where: { code: 'LOC_COMPANY_11_STORE' } });
  const group = await Location.findOne({ where: { code: 'LOC_BATTALION_5_ROOT' } });
  const body = (code, type, parent_location_id, is_stock_holding) => ({ code: `${stamp}_${code}`, name: code, type, parent_location_id, owner_unit_id: null, is_stock_holding, is_active: true, note: null });
  const building = await loc.save(null, body('BLD', 'BUILDING', group.id, false), admin);
  const floor = await loc.save(null, body('FL', 'FLOOR', building.id, false), admin);
  const room1 = await loc.save(null, body('R101', 'ROOM', floor.id, true), admin);
  const room2 = await loc.save(null, body('R102', 'ROOM', floor.id, true), admin);
  await reject(() => loc.save(null, body('R101', 'ROOM', floor.id, true), admin), 409);
  await reject(() => loc.save(building.id, { ...body('BLD', 'BUILDING', room1.id, false) }, admin), 400);
  await reject(() => loc.remove(room1.id, user11), 403);
  await reject(() => loc.remove(building.id, admin), 409);
  const initial = await sequelize.transaction(t => Ledger.create({ unit_id: root.id, location_id: rootStore.id, material_id: material.id, source_id: source.id, condition_id: condition.id, quantity_delta: 100, transaction_type: 'OPENING_BALANCE', reference_type: 'TEST_PHASE6', reference_id: 1, occurred_at: new Date(), created_by: admin.id }, { transaction: t }));
  const item = quantity => ({ material_id: material.id, source_id: source.id, condition_id: condition.id, quantity });
  const date = new Date().toISOString().slice(0, 10);
  const draft = (code, type, company_unit_id, from_location_id, to_location_id, quantity) => ({ code: `${stamp}_${code}`, transfer_type: type, transfer_date: date, company_unit_id, from_location_id, to_location_id, items: [item(quantity)] });
  const issue = await transfer.save(null, draft('ISS', 'ISSUE', c11.id, undefined, room1.id, 20), admin);
  assert.equal(issue.status, 'DRAFT');
  assert.equal((await loc.balances(admin, { unit_id: String(c11.id), material_id: String(material.id) })).length, 0);
  await transfer.post(issue.id, admin);
  await reject(() => transfer.post(issue.id, admin), 409);
  await reject(() => transfer.remove(issue.id, admin), 409);
  const move = await transfer.save(null, draft('MOV', 'INTERNAL_TRANSFER', c11.id, room1.id, room2.id, 7), admin);
  await transfer.post(move.id, admin);
  const remaining = await loc.balances(admin, { location_id: String(building.id), descendants: 'true', unit_id: String(c11.id) });
  assert.deepEqual(remaining.map(r => Number(r.quantity)).sort((a,b) => a-b), [7, 13]);
  const own = await loc.balances(user11, { location_id: String(building.id), descendants: 'true' });
  assert.equal(own.reduce((n, r) => n + Number(r.quantity), 0), 20);
  await reject(() => loc.balances(user11, { unit_id: String(c13.id) }), 403);
  await reject(() => transfer.save(null, draft('BAD', 'INTERNAL_TRANSFER', c11.id, room1.id, room2.id, 99), user11), 403);
  const oversell = await transfer.save(null, draft('OVER', 'INTERNAL_TRANSFER', c11.id, room1.id, room2.id, 99), admin);
  await reject(() => transfer.post(oversell.id, admin), 409);
  assert.equal((await transfer.get(oversell.id)).status, 'DRAFT');
  await transfer.remove(oversell.id, admin);
  // Cách B: cấp về kho rồi điều chuyển; không lập ISSUE thứ hai cho cùng lô.
  const warehouseIssue = await transfer.save(null, draft('STORE', 'ISSUE', c11.id, undefined, companyStore.id, 10), admin);
  await transfer.post(warehouseIssue.id, admin);
  const warehouseMove = await transfer.save(null, draft('STORE_MOVE', 'INTERNAL_TRANSFER', c11.id, companyStore.id, room2.id, 10), admin);
  const [posted, repeated] = await Promise.allSettled([transfer.post(warehouseMove.id, admin), transfer.post(warehouseMove.id, admin)]);
  assert.equal([posted, repeated].filter(r => r.status === 'fulfilled').length, 1);
  assert.equal((await loc.balances(admin, { location_id: String(companyStore.id), unit_id: String(c11.id), material_id: String(material.id) })).length, 0);
  const direct13 = await transfer.save(null, draft('SHARED', 'ISSUE', c13.id, undefined, room1.id, 3), admin);
  await transfer.post(direct13.id, admin);
  const shared = await loc.balances(admin, { location_id: String(room1.id) });
  assert.equal(shared.some(r => String(r.unit_id) === String(c13.id)), true);
  assert.equal((await loc.balances(user11, { location_id: String(room1.id) })).some(r => String(r.unit_id) === String(c13.id)), false);
  assert.equal((await transfer.assets(c11.id, user11, {})).find(r => String(r.id) === String(material.id)).quantity, '30');
  assert.equal((await transfer.assets(c13.id, admin, {})).find(r => String(r.id) === String(material.id)).quantity, '3');
  await reject(() => loc.remove(room1.id, admin), 409);
  const totals = await Ledger.findAll({ where: { material_id: material.id, source_id: source.id, condition_id: condition.id }, attributes: ['quantity_delta'] });
  assert.equal(totals.reduce((n, r) => n + BigInt(r.quantity_delta), 0n) >= 100n, true);
  console.log('Phase 6 service fixture PASS', { opening: initial.id, room1: room1.id, room2: room2.id, issue: issue.id, move: move.id, warehouseIssue: warehouseIssue.id, shared: direct13.id });
}
main().catch(e => { console.error(e); process.exitCode = 1 }).finally(() => sequelize.close());
