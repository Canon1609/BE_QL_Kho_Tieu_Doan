const assert = require('node:assert/strict');
const { sequelize, User, Unit, Location, Material, MaterialCategory, UnitOfMeasure, MaterialSource, StockLedgerEntry: Ledger, BorrowRequest: Request } = require('../src/models');
const borrow = require('../src/services/borrow.service');
const transfers = require('../src/services/transfer.service');
const prefix = `P7_${Date.now()}`;
const qty = async (material, unit, location, line = null) => (await Ledger.findAll({ where: { material_id: material, unit_id: unit, location_id: location, borrow_line_id: line }, attributes: ['quantity_delta'] })).reduce((n, r) => n + BigInt(r.quantity_delta), 0n);
async function main() {
  assert.equal(process.env.DB_NAME, 'ql_kho_tieu_doan_5_phase7_verify', 'Only dedicated test DB is writable');
  const root = await Unit.findOne({ where: { code: 'BATTALION_5' } }), co = await Unit.findOne({ where: { code: 'COMPANY_11' } }), other = await Unit.findOne({ where: { code: 'COMPANY_13' } });
  const user = await User.findOne({ where: { unit_id: root.id } });
  const admin = { ...user.get({ plain: true }), unit: root, role: { code: 'BATTALION_ADMIN' } };
  const company = { ...user.get({ plain: true }), unit_id: co.id, unit: co, role: { code: 'COMPANY_ADMIN' } };
  const outsider = { ...company, unit_id: other.id, unit: other };
  const wh = await Location.findOne({ where: { code: 'LOC_BATTALION_5_WAREHOUSE' } }), store = await Location.findOne({ where: { code: 'LOC_COMPANY_11_STORE' } });
  const rootLocation = await Location.findOne({ where: { code: 'LOC_BATTALION_5_ROOT' } });
  const room = await Location.create({ code: prefix+'ROOM', name: 'Phòng mượn thử', type: 'ROOM', is_active: true, is_stock_holding: true, parent_location_id: rootLocation.id });
  const alternate = await Location.create({ code: prefix+'ALT', name: 'Kho nhận trả khác', type: 'WAREHOUSE', owner_unit_id: root.id, is_active: true, is_stock_holding: true, parent_location_id: rootLocation.id });
  const material = await Material.create({ code: prefix, name: 'Quạt thử Phase 7', category_id: (await MaterialCategory.findOne()).id, unit_id: (await UnitOfMeasure.findOne()).id });
  const source = await MaterialSource.findOne();
  await Ledger.create({ material_id: material.id, source_id: source.id, condition_id: null, unit_id: root.id, location_id: wh.id, quantity_delta: 10, transaction_type: 'NORMAL_RECEIPT', reference_type: 'PHASE7_FIXTURE', reference_id: material.id, occurred_at: new Date(), created_by: admin.id });
  const fields = { code: prefix+'REQ', company_unit_id: co.id, due_date: '2025-01-01', items: [{ material_id: material.id, source_id: source.id, condition_id: null, quantity: 7 }] };
  let r = await borrow.save(null, fields, company);
  assert.equal(await qty(material.id, root.id, wh.id), 10n);
  await assert.rejects(() => borrow.request(r.id, outsider), e => e.statusCode === 403);
  await borrow.transition(r.id, 'SUBMITTED', company);
  await assert.rejects(() => borrow.transition(r.id, 'APPROVED', company), e => e.statusCode === 403);
  await borrow.transition(r.id, 'APPROVED', admin);
  assert.equal(await qty(material.id, root.id, wh.id), 10n);
  await assert.rejects(() => borrow.delivery(r.id, { to_location_id: store.id, from_location_id: store.id }, admin), e => e.statusCode === 400);
  r = await borrow.delivery(r.id, { to_location_id: store.id }, admin);
  const line = r.items[0].id;
  const misplaced = await borrow.returnSave(r.id, null, { items: [{ borrow_line_id: line, from_location_id: room.id, quantity: 1 }] }, admin);
  await assert.rejects(() => borrow.returnPost(r.id, misplaced.id, admin), e => e.statusCode === 409);
  await borrow.returnRemove(r.id, misplaced.id, admin);
  assert.equal(await qty(material.id, root.id, wh.id), 3n);
  assert.equal(await qty(material.id, co.id, store.id, line), 7n);
  assert.equal(await qty(material.id, co.id, store.id), 0n);
  assert.equal((await Ledger.findAll({ where: { borrow_delivery_id: r.delivery.id } })).length, 2);
  await assert.rejects(() => borrow.delivery(r.id, { to_location_id: store.id }, admin), e => e.statusCode === 409);
  const roll = await borrow.save(null, { ...fields, code: prefix+'ROLL', items: [{ ...fields.items[0], quantity: 2 }] }, company);
  await borrow.transition(roll.id, 'SUBMITTED', company);
  await borrow.transition(roll.id, 'APPROVED', admin);
  let inserted = 0;
  Ledger.addHook('beforeCreate', 'p7Rollback', () => { if (++inserted === 2) throw Error('Phase7 injected second ledger error') });
  try { await assert.rejects(() => borrow.delivery(roll.id, { to_location_id: store.id }, admin), /Phase7 injected second ledger error/); }
  finally { Ledger.removeHook('beforeCreate', 'p7Rollback'); }
  assert.equal((await Request.findByPk(roll.id)).status, 'APPROVED');
  assert.equal(await Ledger.count({ where: { transaction_type: 'BORROW', reference_type: 'BORROW_DELIVERY', material_id: material.id } }), 2);
  assert.equal(await qty(material.id, root.id, wh.id), 3n);
  const competitors = await Promise.all(['RACE1', 'RACE2'].map(async suffix => {
    const candidate = await borrow.save(null, { ...fields, code: prefix+suffix, items: [{ ...fields.items[0], quantity: 3 }] }, company);
    await borrow.transition(candidate.id, 'SUBMITTED', company);
    await borrow.transition(candidate.id, 'APPROVED', admin);
    return candidate.id;
  }));
  const race = await Promise.allSettled(competitors.map(cid => borrow.delivery(cid, { to_location_id: store.id }, admin)));
  assert.deepEqual(race.map(x => x.status).sort(), ['fulfilled', 'rejected']);
  assert.equal(await qty(material.id, root.id, wh.id), 0n);
  const winning = race[0].status === 'fulfilled' ? competitors[0] : competitors[1];
  assert.equal(await Ledger.count({ where: { transaction_type: 'BORROW', borrow_delivery_id: { [require('sequelize').Op.ne]: null }, material_id: material.id } }), 4);
  const extra = await borrow.request(winning, admin);
  const cleanup = await borrow.returnSave(winning, null, { items: [{ borrow_line_id: extra.items[0].id, from_location_id: store.id, quantity: 3 }] }, admin);
  await borrow.returnPost(winning, cleanup.id, admin);
  assert.equal(await qty(material.id, root.id, wh.id), 3n);
  const transfer = data => transfers.save(null, { code: prefix+data.code, transfer_type: data.type || 'INTERNAL_TRANSFER', transfer_date: '2026-10-15', company_unit_id: co.id, from_location_id: store.id, to_location_id: room.id, items: [{ material_id: material.id, source_id: source.id, condition_id: null, quantity: data.quantity, ...(data.borrow ? { borrow_line_id: line } : {}) }] }, admin);
  const theft = await transfer({ code: 'NO_TAG', quantity: 1 });
  assert.equal(await qty(material.id, root.id, wh.id) + await qty(material.id, co.id, store.id, line) + await qty(material.id, co.id, room.id, line), 10n);
  await assert.rejects(() => transfers.post(theft.id, admin), e => e.statusCode === 409);
  const move = await transfer({ code: 'MOVE', quantity: 2, borrow: true });
  await transfers.post(move.id, admin);
  assert.equal(await qty(material.id, co.id, store.id, line), 5n);
  assert.equal(await qty(material.id, co.id, room.id, line), 2n);
  assert.equal(await qty(material.id, root.id, wh.id) + await qty(material.id, co.id, store.id, line) + await qty(material.id, co.id, room.id, line), 10n);
  const t = await borrow.returnSave(r.id, null, { items: [{ borrow_line_id: line, from_location_id: room.id, quantity: 2 }] }, admin);
  await borrow.returnPost(r.id, t.id, admin);
  assert.equal((await Request.findByPk(r.id)).status, 'PARTIAL');
  assert.equal(await qty(material.id, co.id, room.id, line), 0n);
  assert.equal(await qty(material.id, root.id, wh.id), 5n);
  assert.equal(await qty(material.id, root.id, wh.id) + await qty(material.id, co.id, store.id, line), 10n);
  const over = await borrow.returnSave(r.id, null, { to_location_id: alternate.id, items: [{ borrow_line_id: line, from_location_id: store.id, quantity: 5 }] }, admin);
  const contender = await borrow.returnSave(r.id, null, { to_location_id: alternate.id, items: [{ borrow_line_id: line, from_location_id: store.id, quantity: 5 }] }, admin);
  const competingReturns = await Promise.allSettled([borrow.returnPost(r.id, over.id, admin), borrow.returnPost(r.id, contender.id, admin)]);
  assert.deepEqual(competingReturns.map(x => x.status).sort(), ['fulfilled', 'rejected']);
  const failedReturn = competingReturns[0].status === 'rejected' ? over.id : contender.id;
  assert.equal((await require('../src/models').BorrowReturn.findByPk(failedReturn)).status, 'DRAFT');
  await borrow.returnRemove(r.id, failedReturn, admin);
  const confirmedReturn = competingReturns[0].status === 'fulfilled' ? over.id : contender.id;
  await assert.rejects(() => borrow.returnPost(r.id, confirmedReturn, admin), e => e.statusCode === 409);
  assert.equal((await Request.findByPk(r.id)).status, 'RETURNED');
  assert.equal(await qty(material.id, root.id, wh.id), 5n);
  assert.equal(await qty(material.id, root.id, alternate.id), 5n);
  assert.equal(await qty(material.id, co.id, store.id, line), 0n);
  const reject = await borrow.save(null, { ...fields, code: prefix+'REJECT' }, company);
  await borrow.transition(reject.id, 'SUBMITTED', company);
  await borrow.transition(reject.id, 'REJECTED', admin, 'Không đáp ứng nhu cầu');
  assert.equal((await Request.findByPk(reject.id)).status, 'REJECTED');
  const cancel = await borrow.save(null, { ...fields, code: prefix+'CANCEL' }, company);
  await borrow.transition(cancel.id, 'CANCEL', company);
  assert.equal((await Request.findByPk(cancel.id)).status, 'CANCELLED');
  assert.equal(await Ledger.count({ where: { material_id: material.id, transaction_type: 'BORROW' } }), 4);
  assert.equal(await Ledger.count({ where: { material_id: material.id, transaction_type: 'RETURN' } }), 6);
  console.log('Phase 7 service lifecycle/ledger separation/scope/partial/concurrency PASS');
}
main().catch(e => { console.error(e); process.exitCode = 1 }).finally(() => sequelize.close());
