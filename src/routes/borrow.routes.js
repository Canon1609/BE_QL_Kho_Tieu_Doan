const router = require('express').Router();
const authenticate = require('../middlewares/authenticate');
const authorize = require('../middlewares/authorizeRoles');
const c = require('../controllers/borrow.controller');
router.use(authenticate, authorize('BATTALION_ADMIN', 'COMPANY_ADMIN'));
router.get('/', c.list);
router.get('/references', c.references);
router.get('/borrowed-at', authorize('BATTALION_ADMIN'), c.borrowedAt);
router.get('/:id', c.detail);
router.post('/', authorize('COMPANY_ADMIN'), c.create);
router.patch('/:id', authorize('COMPANY_ADMIN'), c.update);
router.post('/:id/submit', authorize('COMPANY_ADMIN'), c.action('SUBMITTED'));
router.post('/:id/cancel', authorize('COMPANY_ADMIN'), c.action('CANCEL'));
router.post('/:id/approve', authorize('BATTALION_ADMIN'), c.action('APPROVED'));
router.post('/:id/reject', authorize('BATTALION_ADMIN'), c.action('REJECTED'));
router.post('/:id/deliver', authorize('BATTALION_ADMIN'), c.deliver);
router.post('/:id/returns', c.returnCreate);
router.patch('/:id/returns/:returnId', c.returnUpdate);
router.delete('/:id/returns/:returnId', c.returnRemove);
router.post('/:id/returns/:returnId/post', authorize('BATTALION_ADMIN'), c.returnPost);
module.exports = router;
